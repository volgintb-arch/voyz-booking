export const articleById = (id: string) => ARTICLES.find((a) => a.id === id);

/** Markdown for docs/GUIDE.md — the same articles. */
export function toMarkdown(articles: Article[], legend: [string, string][]): string {
  const out = [
    '# Обучение хозяина Voyz Booking',
    '',
    '<!-- Generated by `npm run guide` from src/help/articles.ts — edit the articles there. -->',
    '',
    'Эти же статьи — в приложении: Настройки → «Обучение».',
    '',
    ...articles.map((a, i) => `${i + 1}. [${a.title}](#${i + 1}) — ${a.summary}`),
    '',
  ];
  articles.forEach((a, i) => {
    out.push('---', '', `<a id="${i + 1}"></a>`, '', `## ${i + 1}. ${a.title}`, '', `_${a.summary} · ${a.minutes} мин_`, '');
    for (const b of a.blocks) {
      if (b.type === 'p') out.push(b.text, '');
      else if (b.type === 'h') out.push(`### ${b.text}`, '');
      else if (b.type === 'steps') out.push(...b.items.map((s, n) => `${n + 1}. ${s}`), '');
      else if (b.type === 'list') out.push(...b.items.map((s) => `- ${s}`), '');
      else if (b.type === 'tip') out.push(`> 💡 ${b.text}`, '');
      else if (b.type === 'warn') out.push(`> ⚠️ ${b.text}`, '');
      else if (b.type === 'legend') out.push('| Полоса | Что значит |', '|---|---|', ...legend.map(([k, v]) => `| ${k} | ${v} |`), '');
    }
  });
  return `${out.join('\n').trimEnd()}\n`;
}
